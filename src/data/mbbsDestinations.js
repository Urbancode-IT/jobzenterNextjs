function buildMbbsAdvantages(countryName) {
  return [
    `NMC-recognised MBBS degree from ${countryName}, valid for practice in India`,
    "Direct admission based on NEET score — no separate entrance exam",
    "Affordable tuition fees compared to private medical colleges in India",
    "English-medium curriculum with modern labs and early clinical exposure",
    "On-campus hostels with Indian food options and a large Indian student community",
    "Visa, SOP, and document support from our MBBS abroad experts",
    "FMGE/NExT exam guidance to practice in India after graduation",
    "End-to-end guidance from university shortlisting to pre-departure",
  ];
}

function buildMbbsFaqs(destination) {
  const { name, eligibility, admissionProcess, careerOpportunities, tuitionFees } = destination;
  return [
    {
      q: `Is an MBBS degree from ${name} recognised in India?`,
      a: `Yes. The universities we recommend in ${name} are NMC-approved, so graduates are eligible to appear for the FMGE/NExT licensing exam to practice in India.`,
    },
    {
      q: `What is the eligibility for MBBS in ${name}?`,
      a: eligibility,
    },
    {
      q: `How does admission to ${name} work?`,
      a: admissionProcess,
    },
    {
      q: `How much does MBBS in ${name} cost per year?`,
      a: `Tuition fees are approximately ${tuitionFees}, in addition to living and hostel expenses. We help you plan the full budget and explore education loan options.`,
    },
    {
      q: `What are my career options after MBBS in ${name}?`,
      a: careerOpportunities,
    },
  ];
}

function buildMbbsJourneyParagraphs(countryName, overview) {
  return [
    `Pursuing MBBS in ${countryName} is a trusted pathway chosen by thousands of Indian students every year. ${overview}`,
    `At Jobzenter, we guide you through NEET-based eligibility checks, university selection, visa processing, and pre-departure preparation — so you can focus on becoming a doctor while we handle the paperwork.`,
  ];
}

export function enrichMbbsDestination(destination) {
  if (!destination) return null;
  return {
    ...destination,
    heroSubtitle:
      destination.heroSubtitle ??
      `Your complete guide to MBBS admission, fees, and career pathway in ${destination.name}.`,
    journeyParagraphs:
      destination.journeyParagraphs ??
      buildMbbsJourneyParagraphs(destination.name, destination.overview),
    advantages: destination.advantages ?? buildMbbsAdvantages(destination.name),
    faqs: destination.faqs ?? buildMbbsFaqs(destination),
  };
}

export function getMbbsDestinationBySlug(slug) {
  const found = mbbsDestinations.find((d) => d.slug === slug) ?? null;
  return enrichMbbsDestination(found);
}

export function getAllMbbsDestinationSlugs() {
  return mbbsDestinations.map((d) => d.slug);
}

export function getOtherMbbsDestinations(currentSlug) {
  return mbbsDestinations.filter((d) => d.slug !== currentSlug);
}
